"""Live-alert path: an incident exactly as the Logic App (infra/logicapp) creates it, plus the rows the real
workspace returns during the injected faults (infra/faults/inject.sh), must reach the right KB and safe runbook."""
from agents.connectors.base import LogAnalyticsClient
from agents.connectors.local import LocalITSM, MockAutomation
from agents.diagnostics import KQL
from agents.models import Incident
from agents.orchestrator import TriageOrchestrator
from agents.remediation import SimulatedApprover


class FakeWorkspace(LogAnalyticsClient):
    def __init__(self, rows):
        self.rows, self.kql = rows, []

    def query(self, kql, resource, hours=24, end=None):
        self.kql.append(kql)
        return self.rows


def _live(title, rule, metric_line):
    # Same shape as infra/logicapp/alert-to-servicenow.json. The rule name matters: it is what separates a
    # disk alert from the (more numerous) CPU alerts on the same CI in retrieval, as in the history.
    return Incident(key="INC0099001", number="INC0099001", short_description=f"[Azure Monitor] Sev2 - {title}",
                    description=("Auto-generated by Azure Monitor action group.\n"
                                 f"Alert rule: {rule} (Sev2)\n"
                                 f"Resource: vm-orders-app-01\n{metric_line}\nFired: 2026-11-16T07:00:00Z\n"
                                 "Alert id: 00000000-0000-0000-0000-000000000000"),
                    ci="vm-orders-app-01", impact=2, urgency=2, category="hardware",
                    opened_at="2026-11-16 07:00:00")


def _triage(inc, rows):
    logs = FakeWorkspace(rows)
    orch = TriageOrchestrator(LocalITSM(), logs, MockAutomation(), approver=SimulatedApprover(), update_tickets=False)
    return orch.triage(inc), logs


def test_live_cpu_alert_restarts_the_runaway_python3():
    rows = [{"CounterName": "% Processor Time", "InstanceName": "total", "avg_CounterValue": 99.1},
            {"Message": "orders-report: python3 report worker stuck in a loop, consuming 100% CPU (pids 2101,2102)"}]
    r, logs = _triage(_live("Percentage CPU > 90% on vm-orders-app-01 for 15 min", "vm-cpu-high",
                            "Percentage CPU: 99.1 (GreaterThan 90) over PT15M"), rows)
    assert "Syslog" in logs.kql[0] and "isfuzzy=true" in logs.kql[0]
    assert r.decision.kb_article == "Troubleshooting high CPU on Azure VMs"
    assert r.remediation.runbook == "RB-VM-Restart-Service" and r.remediation.mode == "automated"
    assert r.remediation.parameters["ServiceName"] == "python3"
    assert r.remediation.parameters["ResourceName"] == "vm-orders-app-01"


def test_live_disk_alert_runs_cleanup():
    rows = [{"CounterName": "% Free Space", "InstanceName": "/", "avg_CounterValue": 4.9},
            {"Message": "orders-app: log rotation disabled: /var/log/skr-orders/orders-debug.log is 53 GB, disk / almost full"}]
    r, _ = _triage(_live("Logical disk free space < 10% on vm-orders-app-01 (/)", "vm-disk-low",
                         "Log query result: 4.9 (LessThan 10) over PT10M"), rows)
    assert r.decision.kb_article == "Resolving low disk space on Azure VMs"
    assert r.remediation.runbook == "RB-VM-Cleanup-Disk" and r.remediation.mode == "automated"



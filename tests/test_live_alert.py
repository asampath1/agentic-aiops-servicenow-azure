def test_live_writes_mark_in_progress_but_eval_writes_keep_state():
    import pytest
    pytest.importorskip("requests")
    from agents.connectors.servicenow import ServiceNowITSM
    inc = Incident(key="INC1", number="INC1", sys_id="abc", short_description="t")
    live = ServiceNowITSM(instance="dev0", user="u", password="p", open_tag="SYNTH-SKR-LIVE", mark_in_progress=True)
    rec = live.update_incident(inc, {}, "note")          # write=False: dry run, nothing sent
    assert rec["body"]["state"] == "2" and rec["sent"] is False
    assert live.open_tag == "SYNTH-SKR-LIVE" and live.tag == "SYNTH-SKR"
    evalset = ServiceNowITSM(instance="dev0", user="u", password="p")
    assert "state" not in evalset.update_incident(inc, {}, "note")["body"]
